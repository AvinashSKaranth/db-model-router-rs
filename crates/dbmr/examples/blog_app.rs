//! Blog Application Backend built with dbmr.
//!
//! Models:
//! - Authors:  `id`, `username`, `email`, `display_name`, `bio`, `is_active`, `created_at`
//! - Posts:    `id`, `author_id`, `title`, `slug`, `content`, `published`, `is_deleted`, `created_at`, `updated_at`
//! - Comments: `id`, `post_id`, `author_id`, `content`, `is_deleted`, `created_at`
//! - Likes:    `id`, `post_id`, `author_id`, `created_at` (composite unique on `[post_id, author_id]`)
//! - Shares:   `id`, `post_id`, `author_id`, `platform`, `created_at`
//!
//! Features exercised:
//! - Full CRUD with Axum REST routers generated by `create_model_router`
//! - Multi-entity relations (`has_many` and `belongs_to`) with eager loading (`?include=...`)
//! - Nested REST routes (`/posts/{post_id}/comments`) via route_layer `Scope` middleware
//! - Validation rules (`email`, `minLength`, `maxLength`, `required`, `in:twitter,linkedin,...`)
//! - Unique constraints (single and composite) with 409 Conflict handling
//! - Soft delete (`safe_delete`) with automatic row filtering on queries
//! - Model hooks (`before_save` for title trimming and automatic slug derivation)
//! - Full-text search (`?search=...`) and field filters (`?published=true`, `?platform=twitter`)
//!
//! Run verification: `cargo run -p dbmr --example blog_app`
//! Serve on :3000:   `cargo run -p dbmr --example blog_app -- --serve`
#![allow(clippy::unwrap_used, clippy::expect_used, clippy::too_many_lines)]

