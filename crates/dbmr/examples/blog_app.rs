/// DDL statements for the blog application.
const BLOG_DDL: &[&str] = &[
    "CREATE TABLE authors (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        username TEXT NOT NULL UNIQUE,
        email TEXT NOT NULL UNIQUE,
        display_name TEXT NOT NULL,
        bio TEXT,
        is_active INTEGER NOT NULL DEFAULT 1,
        created_at TEXT NOT NULL DEFAULT (datetime('now'))
    )",
    "CREATE TABLE posts (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        author_id INTEGER NOT NULL,
        title TEXT NOT NULL,
        slug TEXT NOT NULL UNIQUE,
        content TEXT NOT NULL,
        published INTEGER NOT NULL DEFAULT 0,
        is_deleted INTEGER NOT NULL DEFAULT 0,
        created_at TEXT NOT NULL DEFAULT (datetime('now')),
        updated_at TEXT NOT NULL DEFAULT (datetime('now')),
        FOREIGN KEY(author_id) REFERENCES authors(id)
    )",
    "CREATE TABLE comments (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        post_id INTEGER NOT NULL,
        author_id INTEGER NOT NULL,
        content TEXT NOT NULL,
        is_deleted INTEGER NOT NULL DEFAULT 0,
        created_at TEXT NOT NULL DEFAULT (datetime('now')),
        FOREIGN KEY(post_id) REFERENCES posts(id),
        FOREIGN KEY(author_id) REFERENCES authors(id)
    )",
    "CREATE TABLE likes (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        post_id INTEGER NOT NULL,
        author_id INTEGER NOT NULL,
        created_at TEXT NOT NULL DEFAULT (datetime('now')),
        CONSTRAINT uq_post_author UNIQUE (post_id, author_id),
        FOREIGN KEY(post_id) REFERENCES posts(id),
        FOREIGN KEY(author_id) REFERENCES authors(id)
    )",
    "CREATE TABLE shares (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        post_id INTEGER NOT NULL,
        author_id INTEGER NOT NULL,
        platform TEXT NOT NULL,
        created_at TEXT NOT NULL DEFAULT (datetime('now')),
        FOREIGN KEY(post_id) REFERENCES posts(id),
        FOREIGN KEY(author_id) REFERENCES authors(id)
    )",
];

/// Initialise in-memory SQLite database and execute the Blog DDL.
pub async fn setup_database() -> dbmr::Result<Arc<dyn DatabaseAdapter>> {
    let db = SqliteAdapter::connect("sqlite::memory:").await?;
    for sql in BLOG_DDL {
        db.query(sql, &[]).await?;
    }
    Ok(db)
}

/// The built Blog models ready for router creation or direct queries.
pub struct BlogModels {
    pub authors: Model,
    pub posts: Model,
    pub comments: Model,
    pub likes: Model,
    pub shares: Model,
}

/// Build all Blog models with rules, unique constraints, hooks, and relations.
pub fn build_blog_models(db: Arc<dyn DatabaseAdapter>) -> dbmr::Result<BlogModels> {
    // 1. Authors model
    let authors = Model::builder(db.clone(), "authors")
        .column("id", "integer")
        .column("username", "required|string|minLength:3|maxLength:30")
        .column("email", "required|email")
        .column("display_name", "required|string|maxLength:100")
        .column("bio", "string|nullable")
        .column("is_active", "boolean")
        .created_at("created_at")
        .unique(["username"])
        .unique(["email"])
        .search_columns(["username", "display_name", "bio"])
        .build()?;

    // 2. Posts model with before_save hook to trim title and derive slug
    let posts = Model::builder(db.clone(), "posts")
        .column("id", "integer")
        .column("author_id", "required|integer")
        .column("title", "required|string|maxLength:120")
        .column("slug", "required|string|maxLength:150")
        .column("content", "required|string")
        .column("published", "boolean")
        .safe_delete("is_deleted")
        .created_at("created_at")
        .modified_at("updated_at")
        .unique(["slug"])
        .search_columns(["title", "content"])
        .hooks(ModelHooks::new().before_save(|mut row, _ctx| async move {
            if let Some(DbValue::Text(t)) = row.get("title") {
                let trimmed = t.trim().to_string();
                row.insert("title".into(), trimmed.clone().into());
                let needs_slug = match row.get("slug") {
                    None | Some(DbValue::Null) => true,
                    Some(DbValue::Text(s)) => s.trim().is_empty(),
                    _ => false,
                };
                if needs_slug {
                    let slug = trimmed.to_lowercase().replace(' ', "-");
                    row.insert("slug".into(), slug.into());
                }
            }
            Ok(row)
        }))
        .build()?;

    // 3. Comments model with soft delete
    let comments = Model::builder(db.clone(), "comments")
        .column("id", "integer")
        .column("post_id", "required|integer")
        .column("author_id", "required|integer")
        .column("content", "required|string|maxLength:1000")
        .safe_delete("is_deleted")
        .created_at("created_at")
        .search_columns(["content"])
        .build()?;

    // 4. Likes model with composite unique constraint on (post_id, author_id)
    let likes = Model::builder(db.clone(), "likes")
        .column("id", "integer")
        .column("post_id", "required|integer")
        .column("author_id", "required|integer")
        .created_at("created_at")
        .unique(["post_id", "author_id"])
        .build()?;

    // 5. Shares model with platform validation enum
    let shares = Model::builder(db, "shares")
        .column("id", "integer")
        .column("post_id", "required|integer")
        .column("author_id", "required|integer")
        .column(
            "platform",
            "required|string|in:twitter,linkedin,reddit,facebook,direct",
        )
        .created_at("created_at")
        .build()?;

    // Wire up relations
    let authors = authors.has_many("posts", &posts, "author_id");
    let posts = posts
        .belongs_to("author", &authors, "author_id")
        .has_many("comments", &comments, "post_id")
        .has_many("likes", &likes, "post_id")
        .has_many("shares", &shares, "post_id");

    let comments =
        comments
            .belongs_to("post", &posts, "post_id")
            .belongs_to("author", &authors, "author_id");

    let likes =
        likes
            .belongs_to("post", &posts, "post_id")
            .belongs_to("author", &authors, "author_id");

    let shares =
        shares
            .belongs_to("post", &posts, "post_id")
            .belongs_to("author", &authors, "author_id");

    Ok(BlogModels {
        authors,
        posts,
        comments,
        likes,
        shares,
    })
}

/// Scope middleware for nested `/posts/{post_id}/comments` route.
/// Adds `post_id` from the path parameter to the request Scope.
async fn post_comments_scope(
    Path(p): Path<HashMap<String, String>>,
    mut req: Request,
    next: Next,
) -> Response {
    let mut scope = req.extensions().get::<Scope>().cloned().unwrap_or_default();
    scope.0.insert("post_id".into(), json!(p["post_id"]));
    req.extensions_mut().insert(scope);
    next.run(req).await
}

/// Build the Axum router for the complete Blog Application.
pub fn build_blog_router(models: BlogModels) -> Router {
    Router::new()
        .nest("/authors", create_model_router(models.authors))
        .nest("/posts", create_model_router(models.posts))
        .nest("/comments", create_model_router(models.comments.clone()))
        .nest("/likes", create_model_router(models.likes))
        .nest("/shares", create_model_router(models.shares))
        // Nested route: /posts/{post_id}/comments
        .nest(
            "/posts/{post_id}/comments",
            create_model_router(models.comments)
                .route_layer(middleware::from_fn(post_comments_scope)),
        )
}

/// Dispatch one HTTP request to the router and extract status, headers, and parsed JSON.
pub async fn send_request(
    app: &Router,
    method: &str,
    uri: &str,
    body: Option<Value>,
) -> (StatusCode, HeaderMap, Value) {
    let req = Request::builder()
        .method(method)
        .uri(uri)
        .header("content-type", "application/json");

    let body = body.map_or_else(Body::empty, |b| Body::from(b.to_string()));
    let req = req.body(body).unwrap();
    let res = app.clone().oneshot(req).await.unwrap();
    let (status, headers) = (res.status(), res.headers().clone());
    let bytes = axum::body::to_bytes(res.into_body(), 1 << 20)
        .await
        .unwrap();
    let text = String::from_utf8(bytes.to_vec()).unwrap();
    let json_val = if text.is_empty() {
        Value::Null
    } else {
        serde_json::from_str(&text).unwrap_or(Value::String(text))
    };
    (status, headers, json_val)
}

/// Run end-to-end verification of all Blog features.
pub async fn run_blog_tests(app: &Router) {
    println!("--- 1. Author Registration and Validation ---");
    // Valid Author 1: Alice
    let (status, _, alice) = send_request(
        app,
        "POST",
        "/authors",
        Some(json!({
            "username": "alice",
            "email": "alice@example.com",
            "display_name": "Alice Karanth",
            "bio": "Systems programmer & Rust enthusiast"
        })),
    )
    .await;
    assert_eq!(status, StatusCode::OK, "Create Alice: {alice}");
    assert_eq!(alice["id"], 1);
    assert_eq!(alice["username"], "alice");

    // Valid Author 2: Bob
    let (status, _, bob) = send_request(
        app,
        "POST",
        "/authors",
        Some(json!({
            "username": "bob",
            "email": "bob@example.com",
            "display_name": "Bob Builder",
            "bio": "Distributed systems engineer"
        })),
    )
    .await;
    assert_eq!(status, StatusCode::OK, "Create Bob: {bob}");
    assert_eq!(bob["id"], 2);

    // Validation: Invalid email format -> 422
    let (status, _, err) = send_request(
        app,
        "POST",
        "/authors",
        Some(json!({
            "username": "charlie",
            "email": "not-an-email",
            "display_name": "Charlie"
        })),
    )
    .await;
    assert_eq!(status, StatusCode::UNPROCESSABLE_ENTITY);
    assert!(err["message"].as_str().unwrap().contains("email"));

    // Validation: Username too short (< 3 chars) -> 422
    let (status, _, err) = send_request(
        app,
        "POST",
        "/authors",
        Some(json!({
            "username": "ab",
            "email": "ab@example.com",
            "display_name": "AB"
        })),
    )
    .await;
    assert_eq!(status, StatusCode::UNPROCESSABLE_ENTITY);
    assert!(err["message"].as_str().unwrap().contains("less than 3"));

    // Unique: Duplicate email -> 409
    let (status, _, _err) = send_request(
        app,
        "POST",
        "/authors",
        Some(json!({
            "username": "alice2",
            "email": "alice@example.com",
            "display_name": "Alice Clone"
        })),
    )
    .await;
    assert_eq!(status, StatusCode::CONFLICT);
    println!("  Author validation and unique constraints: PASSED");

    println!("--- 2. Post Creation, Hooks and Constraints ---");
    // Create Post for Alice; test that whitespace is trimmed and slug is auto-generated
    let (status, _, post1) = send_request(
        app,
        "POST",
        "/posts",
        Some(json!({
            "author_id": 1,
            "title": "  Building Fast Microservices in Rust  ",
            "content": "Rust offers memory safety without garbage collection overhead.",
            "published": true
        })),
    )
    .await;
    assert_eq!(status, StatusCode::OK, "Create Post 1: {post1}");
    assert_eq!(post1["id"], 1);
    assert_eq!(post1["title"], "Building Fast Microservices in Rust");
    assert_eq!(post1["slug"], "building-fast-microservices-in-rust");
    assert_eq!(post1["published"], true);

    // Create Draft Post for Bob
    let (status, _, post2) = send_request(
        app,
        "POST",
        "/posts",
        Some(json!({
            "author_id": 2,
            "title": "Draft Architecture Notes",
            "content": "Work in progress thoughts on Raft consensus.",
            "published": false
        })),
    )
    .await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(post2["slug"], "draft-architecture-notes");

    // Validation: Title exceeds maxLength (120 chars) -> 422
    let long_title = "A".repeat(125);
    let (status, _, err) = send_request(
        app,
        "POST",
        "/posts",
        Some(json!({
            "author_id": 1,
            "title": long_title,
            "content": "Too long title test"
        })),
    )
    .await;
    assert_eq!(status, StatusCode::UNPROCESSABLE_ENTITY);
    assert!(err["message"]
        .as_str()
        .unwrap()
        .contains("greater than 120"));
    println!("  Post creation, slug hook & title length validation: PASSED");

    println!("--- 3. Comments (Direct and Nested Route) ---");
    // Direct comment on Post 1 by Bob
    let (status, _, comment1) = send_request(
        app,
        "POST",
        "/comments",
        Some(json!({
            "post_id": 1,
            "author_id": 2,
            "content": "Great article! Very well explained."
        })),
    )
    .await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(comment1["id"], 1);
    assert_eq!(comment1["post_id"], 1);

    // Nested route: POST /posts/1/comments (Alice replying to Post 1)
    let (status, _, comment2) = send_request(
        app,
        "POST",
        "/posts/1/comments",
        Some(json!({
            "author_id": 1,
            "content": "Thanks Bob, glad you enjoyed it!"
        })),
    )
    .await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(comment2["id"], 2);
    assert_eq!(comment2["post_id"], 1);

    // Nested route: GET /posts/1/comments (should return both comments for post 1)
    let (status, _, post_comments) = send_request(app, "GET", "/posts/1/comments", None).await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(post_comments["count"], 2);

    // Nested route: GET /posts/2/comments (should return 0 comments for post 2)
    let (status, _, post2_comments) = send_request(app, "GET", "/posts/2/comments", None).await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(post2_comments["count"], 0);
    println!("  Comments and nested routes (/posts/{{id}}/comments): PASSED");

    println!("--- 4. Likes and Composite Unique Constraint ---");
    // Bob likes Post 1
    let (status, _, like1) = send_request(
        app,
        "POST",
        "/likes",
        Some(json!({ "post_id": 1, "author_id": 2 })),
    )
    .await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(like1["id"], 1);

    // Alice likes Post 1
    let (status, _, like2) = send_request(
        app,
        "POST",
        "/likes",
        Some(json!({ "post_id": 1, "author_id": 1 })),
    )
    .await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(like2["id"], 2);

    // Bob attempts to like Post 1 AGAIN -> 409 Conflict (composite unique key violated)
    let (status, _, err) = send_request(
        app,
        "POST",
        "/likes",
        Some(json!({ "post_id": 1, "author_id": 2 })),
    )
    .await;
    assert_eq!(status, StatusCode::CONFLICT);
    assert!(err["message"].as_str().unwrap().contains("Duplicate value"));
    println!("  Likes and composite unique key [post_id, author_id]: PASSED");

    println!("--- 5. Shares and Platform Enum Validation ---");
    // Share on Twitter (valid)
    let (status, _, s1) = send_request(
        app,
        "POST",
        "/shares",
        Some(json!({ "post_id": 1, "author_id": 2, "platform": "twitter" })),
    )
    .await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(s1["platform"], "twitter");

    // Share on LinkedIn (valid)
    let (status, _, s2) = send_request(
        app,
        "POST",
        "/shares",
        Some(json!({ "post_id": 1, "author_id": 1, "platform": "linkedin" })),
    )
    .await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(s2["platform"], "linkedin");

    // Invalid platform ("tiktok" not in list) -> 422
    let (status, _, err) = send_request(
        app,
        "POST",
        "/shares",
        Some(json!({ "post_id": 1, "author_id": 2, "platform": "tiktok" })),
    )
    .await;
    assert_eq!(status, StatusCode::UNPROCESSABLE_ENTITY);
    assert!(err["message"].as_str().unwrap().contains("invalid"));
    println!("  Shares platform validation: PASSED");

    println!("--- 6. Eager Loading Relations (?include=...) ---");
    // Include author, comments, likes, and shares on Post 1
    let (status, _, post_included) = send_request(
        app,
        "GET",
        "/posts/1?include=author,comments,likes,shares",
        None,
    )
    .await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(post_included["author"]["username"], "alice");
    assert_eq!(post_included["comments"].as_array().unwrap().len(), 2);
    assert_eq!(post_included["likes"].as_array().unwrap().len(), 2);
    assert_eq!(post_included["shares"].as_array().unwrap().len(), 2);

    // Include posts on Author 1 (Alice)
    let (status, _, author_included) =
        send_request(app, "GET", "/authors/1?include=posts", None).await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(author_included["posts"].as_array().unwrap().len(), 1);
    assert_eq!(
        author_included["posts"][0]["slug"],
        "building-fast-microservices-in-rust"
    );
    println!("  Relations eager loading (?include=author,comments,likes,shares): PASSED");

    println!("--- 7. Search and Filtering ---");
    // Search posts: ?search=Microservices
    let (status, _, res) = send_request(app, "GET", "/posts?search=Microservices", None).await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(res["count"], 1);

    // Filter posts: ?published=true vs ?published=false
    let (status, _, res) = send_request(app, "GET", "/posts?published=true", None).await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(res["count"], 1);

    let (status, _, res) = send_request(app, "GET", "/posts?published=false", None).await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(res["count"], 1);

    // Filter shares by platform: ?platform=twitter
    let (status, _, res) = send_request(app, "GET", "/shares?platform=twitter", None).await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(res["count"], 1);
    println!("  Search & field filtering: PASSED");

    println!("--- 8. Soft Delete Semantics ---");
    // Delete Post 2 (soft delete)
    let (status, _, _) = send_request(app, "DELETE", "/posts/2", None).await;
    assert_eq!(status, StatusCode::OK);

    // Subsequent GET /posts/2 must return 404 (hidden by safe delete)
    let (status, _, _) = send_request(app, "GET", "/posts/2", None).await;
    assert_eq!(status, StatusCode::NOT_FOUND);

    // List /posts must now only return Post 1
    let (status, _, res) = send_request(app, "GET", "/posts", None).await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(res["count"], 1);
    assert_eq!(res["data"][0]["id"], 1);
    println!("  Soft delete safe_delete: PASSED");

    println!("\n All Blog Application tests passed successfully!");
}

#[tokio::main]
async fn main() -> dbmr::Result<()> {
    let db = setup_database().await?;
    let models = build_blog_models(db)?;
    let app = build_blog_router(models);

    if std::env::args().any(|a| a == "--serve") {
        let addr = "127.0.0.1:3000";
        let listener = tokio::net::TcpListener::bind(addr)
            .await
            .expect("bind :3000");
        println!("🚀 Blog App API server running at http://{addr}");
        println!("Available endpoints:");
        println!("  GET, POST          /authors");
        println!("  GET, PUT, PATCH    /authors/:id");
        println!("  GET, POST          /posts (supports ?include=author,comments,likes,shares)");
        println!("  GET, PUT, PATCH    /posts/:id");
        println!("  DELETE             /posts/:id (soft delete)");
        println!("  GET, POST          /posts/:post_id/comments (nested route)");
        println!("  GET, POST          /comments");
        println!("  GET, POST          /likes (composite unique per post+author)");
        println!("  GET, POST          /shares (platform in:twitter,linkedin,...)");
        axum::serve(listener, app).await.expect("serve error");
        return Ok(());
    }

    run_blog_tests(&app).await;
    Ok(())
}
