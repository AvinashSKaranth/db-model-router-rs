async fn get_oracle() -> Option<std::sync::Arc<OracleAdapter>> {
    // Oracle container credentials from docker-compose.yml:
    // service FREEPDB1, user SYSTEM, password oracle
    match OracleAdapter::connect("127.0.0.1", 1521, "FREEPDB1", "SYSTEM", "oracle").await {
        Ok(a) => Some(a),
        Err(e) => {
            panic!("Oracle container not reachable or not ready: {e}")
        }
    }
}

#[tokio::test]
#[ignore = "requires live service: docker compose up, then cargo test --all-features -- --ignored"]
async fn test_oracle_crud() {
    let Some(adapter) = get_oracle().await else {
        return;
    };

    // 1. Create table safely
    let _ = adapter
        .query(
            r"
            BEGIN
               EXECUTE IMMEDIATE 'DROP TABLE TEST_ORACLE_USERS';
            EXCEPTION
               WHEN OTHERS THEN
                  IF SQLCODE != -942 THEN
                     RAISE;
                  END IF;
            END;
            ",
            &[],
        )
        .await;

    adapter
        .query(
            r"
            CREATE TABLE TEST_ORACLE_USERS (
                ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                NAME VARCHAR2(255) NOT NULL,
                SCORE NUMBER NOT NULL,
                DELETED NUMBER DEFAULT 0
            )
            ",
            &[],
        )
        .await
        .unwrap();

    // 2. Insert rows
    let mut row1 = RowMap::new();
    row1.insert(
        CompactString::new("name"),
        DbValue::Text("Alice".to_string()),
    );
    row1.insert(CompactString::new("score"), DbValue::Int(100));

    let mut row2 = RowMap::new();
    row2.insert(CompactString::new("name"), DbValue::Text("Bob".to_string()));
    row2.insert(CompactString::new("score"), DbValue::Int(80));

    let summary = adapter
        .insert_rows("test_oracle_users", &[row1, row2], &[])
        .await
        .unwrap();
    assert_eq!(summary.rows, 2);

    // 3. Count
    let total = adapter
        .count("test_oracle_users", &FilterExpr::default(), None)
        .await
        .unwrap();
    assert_eq!(total, 2);

    // 4. Query with filter and sort
    let mut filter = FilterExpr::default();
    filter.groups.push(vec![Condition {
        column: CompactString::new("name"),
        operator: Operator::Eq,
        value: DbValue::Text("Alice".to_string()),
    }]);

    let res = adapter
        .get(
            "test_oracle_users",
            &filter,
            &[SortKey {
                column: CompactString::new("score"),
                direction: SortDirection::Desc,
            }],
            None,
            GetOptions::default(),
        )
        .await
        .unwrap();

    assert_eq!(res.count, 1);
    assert_eq!(
        res.data[0].get("name").unwrap(),
        &DbValue::Text("Alice".to_string())
    );

    // 6. Remove rows with safe delete
    let remove_summary = adapter
        .remove_rows("test_oracle_users", &filter, Some("deleted"))
        .await
        .unwrap();
    assert_eq!(remove_summary.rows, 1);

    let active_count = adapter
        .count("test_oracle_users", &FilterExpr::default(), Some("deleted"))
        .await
        .unwrap();
    assert_eq!(active_count, 1);
}

