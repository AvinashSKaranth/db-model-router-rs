fn err<T>(r: dbmr::core::error::Result<T>) -> String {
    match r {
        Ok(_) => panic!("expected an error"),
        Err(e) => e.message().to_string(),
    }
}

async fn ora() -> std::sync::Arc<OracleAdapter> {
    OracleAdapter::connect("127.0.0.1", 1521, "FREEPDB1", "SYSTEM", "oracle")
        .await
        .expect("oracle connect")
}

async fn recreate(a: &OracleAdapter, table: &str, ddl: &str) {
    a.query(
        &format!(
            "BEGIN EXECUTE IMMEDIATE 'DROP TABLE {table}'; \
             EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;"
        ),
        &[],
    )
    .await
    .unwrap();
    a.query(ddl, &[]).await.unwrap();
}

#[tokio::test]
#[ignore = "requires live Oracle"]
async fn cov_oracle_decodes_every_column_type() {
    let a = ora().await;
    recreate(
        &a,
        "COV_ORA_TYPES",
        "CREATE TABLE COV_ORA_TYPES (
            ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            N NUMBER(10), DC NUMBER(10,2), FL NUMBER, S VARCHAR2(50), R RAW(16),
            D DATE, TS TIMESTAMP, TZ TIMESTAMP WITH TIME ZONE, FLAG NUMBER(1), C CLOB, BL BLOB)",
    )
    .await;

    // oracle-rs limitation (not adapter code): BINARY_FLOAT/BINARY_DOUBLE come back as
    // undecodable bytes, so those column types are not used here.
    let dec = rust_decimal::Decimal::new(12345, 2);
    let s = a
        .insert_rows(
            "cov_ora_types",
            &[dbmr::core::types::row([
                ("n", DbValue::Int(-42)),
                ("dc", DbValue::Decimal(dec)),
                ("fl", DbValue::Float(1.5)),
                ("s", DbValue::Text("hello".into())),
                ("r", DbValue::Bytes(vec![0, 1, 255])),
                ("d", DbValue::Null),
                // Booleans bind as 1/0 (a BOOLEAN bind used to hang the session).
                ("flag", DbValue::Bool(true)),
                ("c", DbValue::Text("long text".into())),
                ("bl", DbValue::Bytes(vec![4, 5])),
            ])],
            &[],
        )
        .await
        .unwrap();
    // Single insert returns the stored record (found by ROWID); NUMBERs decode as numbers.
    let rec = s.record.expect("stored record");
    assert_eq!(s.id, Some(DbValue::Int(1)));
    assert_eq!(rec.get("n"), Some(&DbValue::Int(-42)));
    assert_eq!(rec.get("dc"), Some(&DbValue::Decimal(dec)));
    assert_eq!(
        rec.get("fl"),
        Some(&DbValue::Decimal(rust_decimal::Decimal::new(15, 1)))
    );
    assert_eq!(rec.get("s"), Some(&DbValue::Text("hello".into())));
    assert_eq!(rec.get("r"), Some(&DbValue::Bytes(vec![0, 1, 255])));
    assert_eq!(rec.get("d"), Some(&DbValue::Null));
    assert_eq!(rec.get("flag"), Some(&DbValue::Int(1)));
    // LOB columns are read through their locators.
    assert_eq!(rec.get("c"), Some(&DbValue::Text("long text".into())));
    assert_eq!(rec.get("bl"), Some(&DbValue::Bytes(vec![4, 5])));
    assert_eq!(
        a.count("cov_ora_types", &FilterExpr::eq("flag", true), None)
            .await
            .unwrap(),
        1
    );
    // A NUMBER too large for i128 and Decimal keeps its digits as text.
    let rows = a.query("SELECT 1e50 AS huge FROM dual", &[]).await.unwrap();
    assert_eq!(
        rows[0].get("huge"),
        Some(&DbValue::Text(format!("1{}", "0".repeat(50))))
    );

    // Dates and timestamps read back as ISO-8601 UTC, like PostgreSQL TIMESTAMP.
    a.query(
        "UPDATE COV_ORA_TYPES SET D = TIMESTAMP '2024-01-02 03:04:05',          TS = TIMESTAMP '2024-01-02 03:04:05.678', TZ = TIMESTAMP '2024-01-02 03:04:05 +02:00'",
        &[],
    )
    .await
    .unwrap();
    let rows = a
        .query("select d, ts, tz FROM COV_ORA_TYPES", &[])
        .await
        .unwrap();
    let text = |s: &str| Some(DbValue::Text(s.into()));
    assert_eq!(rows[0].get("d").cloned(), text("2024-01-02T03:04:05.000Z"));
    assert_eq!(rows[0].get("ts").cloned(), text("2024-01-02T03:04:05.678Z"));
    assert_eq!(rows[0].get("tz").cloned(), text("2024-01-02T01:04:05.000Z"));

    // WITH queries return rows too (they used to be executed as statements).
    let rows = a
        .query("WITH x AS (SELECT 1 AS v FROM dual) SELECT v FROM x", &[])
        .await
        .unwrap();
    assert_eq!(rows[0].get("v"), Some(&DbValue::Int(1)));

    // Json and Null binds.
    let rows = a
        .query(
            "SELECT :1 AS j, NVL(:2, 'none') AS n FROM dual",
            &[DbValue::Json(serde_json::json!({"k": 1})), DbValue::Null],
        )
        .await
        .unwrap();
    assert_eq!(
        rows[0].get("j"),
        Some(&DbValue::Json(serde_json::json!({"k": 1})))
    );
    assert_eq!(rows[0].get("n"), Some(&DbValue::Text("none".into())));
}

#[tokio::test]
#[ignore = "requires live Oracle"]
async fn cov_oracle_paging_upsert_and_errors() {
    let a = ora().await;
    recreate(
        &a,
        "COV_ORA_OPS",
        "CREATE TABLE COV_ORA_OPS (
            ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            CODE VARCHAR2(20) NOT NULL UNIQUE, SCORE NUMBER, DELETED NUMBER DEFAULT 0)",
    )
    .await;
    let t = "cov_ora_ops";
    let mk = |code: &str, score: i128| {
        dbmr::core::types::row([
            ("code", DbValue::Text(code.into())),
            ("score", DbValue::Int(score)),
        ])
    };

    let s = a.insert_rows(t, &[], &[]).await.unwrap();
    assert_eq!(
        (s.rows, s.message.as_str()),
        (0, "0 Cov Ora Opss are saved")
    );
    assert_eq!(a.upsert_rows(t, &[], &[]).await.unwrap().rows, 0);
    let s = a
        .insert_rows(t, &[mk("a", 1), mk("b", 2), mk("c", 3)], &[])
        .await
        .unwrap();
    assert_eq!((s.rows, s.id), (3, None));

    let by_code = [SortKey {
        column: CompactString::new("code"),
        direction: SortDirection::Desc,
    }];
    let page = a
        .list(t, &FilterExpr::empty(), &by_code, None, 1, 1)
        .await
        .unwrap();
    assert_eq!((page.data.len(), page.count), (1, 3));
    assert_eq!(page.data[0].get("code"), Some(&DbValue::Text("b".into())));
    let page = a
        .list(t, &FilterExpr::empty(), &[], None, 0, 2)
        .await
        .unwrap();
    assert_eq!((page.data.len(), page.count), (2, 3));
    let first = a
        .get(
            t,
            &FilterExpr::empty(),
            &by_code,
            None,
            GetOptions {
                limit: Some(1),
                ..Default::default()
            },
        )
        .await
        .unwrap();
    assert_eq!(first.data[0].get("code"), Some(&DbValue::Text("c".into())));
    let liked = a
        .count(
            t,
            &FilterExpr::default().and("code", Operator::Like, "A"),
            None,
        )
        .await
        .unwrap();
    assert_eq!(liked, 1, "LIKE is case-insensitive on Oracle");
    let dec = rust_decimal::Decimal::new(25, 1);
    assert_eq!(
        a.count(
            t,
            &FilterExpr::default().and("score", Operator::Gt, dec),
            None
        )
        .await
        .unwrap(),
        1
    );
    assert_eq!(
        a.count(
            t,
            &FilterExpr::default().and("score", Operator::Lt, 1.5),
            None
        )
        .await
        .unwrap(),
        1
    );

    // Upsert on `code`: update existing, insert new; a partial key is a plain insert;
    // a row holding only key columns has nothing to update.
    let s = a
        .upsert_rows(t, &[mk("a", 10), mk("d", 4)], &[vec!["code".into()]])
        .await
        .unwrap();
    assert_eq!(s.rows, 2);
    assert_eq!(
        a.count(t, &FilterExpr::eq("score", 10), None)
            .await
            .unwrap(),
        1
    );
    a.upsert_rows(t, &[mk("e", 5)], &[vec!["code".into(), "absent".into()]])
        .await
        .unwrap();
    a.upsert_rows(t, &[dbmr::core::types::row([("id", DbValue::Int(1))])], &[])
        .await
        .unwrap();
    assert_eq!(a.count(t, &FilterExpr::empty(), None).await.unwrap(), 5);

    let s = a
        .remove_rows(t, &FilterExpr::eq("code", "e"), Some("deleted"))
        .await
        .unwrap();
    assert_eq!(s.rows, 1);
    assert_eq!(
        a.count(t, &FilterExpr::empty(), Some("deleted"))
            .await
            .unwrap(),
        4
    );
    let s = a
        .remove_rows(t, &FilterExpr::eq("code", "d"), None)
        .await
        .unwrap();
    assert_eq!((s.rows, s.message.as_str()), (1, "1 cov_ora_ops removed"));

    // Errors.
    let e = err(a.query("SELECT * FROM COV_ORA_MISSING", &[]).await);
    assert!(e.starts_with("Oracle query error"), "{e}");
    let e = err(a.query("DELETE FROM COV_ORA_MISSING", &[]).await);
    assert!(e.starts_with("Oracle execute error"), "{e}");
    let e = err(a.insert_rows(t, &[mk("a", 1)], &[]).await);
    assert!(e.starts_with("Oracle execute error"), "{e}");
    assert_eq!(a.escape_id("a\"b"), "\"A\"\"B\"");

    assert!(a.is_connected().await);
    a.disconnect().await.unwrap();
    assert!(!a.is_connected().await);

    let e = err(OracleAdapter::connect("127.0.0.1", 1521, "FREEPDB1", "SYSTEM", "wrong").await);
    assert!(e.starts_with("Oracle connection error"), "{e}");
}

#[tokio::test]
#[ignore = "requires live Oracle"]
async fn cov_oracle_reconnects_after_session_is_killed() {
    let a = ora().await;
    let me = a
        .query(
            "SELECT SYS_CONTEXT('USERENV','SID') AS sid, s.serial# AS serial FROM v$session s \
             WHERE s.sid = SYS_CONTEXT('USERENV','SID')",
            &[],
        )
        .await
        .unwrap();
    let (sid, serial) = (me[0]["sid"].to_string(), me[0]["serial"].to_string());
    let killer = ora().await;
    killer
        .query(
            &format!("ALTER SYSTEM KILL SESSION '{sid},{serial}' IMMEDIATE"),
            &[],
        )
        .await
        .unwrap();
    // The first call on the dead session fails; the adapter then reconnects.
    let _ = a.query("SELECT 1 AS one FROM dual", &[]).await;
    let rows = a.query("SELECT 1 AS one FROM dual", &[]).await.unwrap();
    assert_eq!(rows[0].get("one"), Some(&DbValue::Int(1)));
    assert!(a.is_connected().await);
}

